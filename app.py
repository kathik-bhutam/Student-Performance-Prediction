
import streamlit as st
import pandas as pd
import joblib

# Load trained model
model = joblib.load("models/student_model.pkl")

# Page configuration
st.set_page_config(
    page_title="Student Performance Prediction",
    page_icon="🎓",
    layout="wide"
)

# Sidebar
st.sidebar.title("About Project")
st.sidebar.write("Student Performance Prediction")
st.sidebar.write("Machine Learning Model: Linear Regression")
st.sidebar.write("Built using Python and Streamlit")

# Main heading
st.title("🎓 Student Performance Prediction")
st.write("Predict student final marks using academic information.")

st.divider()

# Input section
st.subheader("Enter Student Details")

col1, col2 = st.columns(2)

with col1:
    study_hours = st.number_input(
        "Study Hours",
        min_value=0.0,
        max_value=24.0,
        value=5.0
    )

    attendance = st.number_input(
        "Attendance (%)",
        min_value=0.0,
        max_value=100.0,
        value=80.0
    )

with col2:
    previous_marks = st.number_input(
        "Previous Marks",
        min_value=0.0,
        max_value=100.0,
        value=60.0
    )

    assignment_score = st.number_input(
        "Assignment Score",
        min_value=0.0,
        max_value=100.0,
        value=70.0
    )

st.divider()

# Prediction
if st.button("Predict Final Marks", type="primary"):

    new_student = pd.DataFrame([{
        "study_hours": study_hours,
        "attendance": attendance,
        "previous_marks": previous_marks,
        "assignment_score": assignment_score
    }])

    prediction = model.predict(new_student)[0]

    st.subheader("Prediction Result")
    st.metric("Predicted Final Marks", f"{prediction:.2f}")

    st.info(
        "This prediction is an estimate generated by a "
        "Linear Regression model."
    )
